-- Synthetic legacy commercial-loan source system for Ontology Mapping demos.
-- PostgreSQL compatible. All records are fictional.
-- Deliberately uses legacy-style table/column names.

DROP TABLE IF EXISTS LN_PAY_TXN, LN_COV_XREF, COV_MST, COLL_LINK, COLL_MST,
                     GUAR_XREF, LN_RATING_HIST, LN_AGR, LN_ACCT, LN_FAC,
                     CUST_GRP_XREF, CUST_MST CASCADE;

CREATE TABLE CUST_MST (
  CUST_NO        VARCHAR(12) PRIMARY KEY,
  LEGAL_NM       VARCHAR(120) NOT NULL,
  CUST_TYP       VARCHAR(20) NOT NULL, -- CORP / SME
  TAX_CNTRY      CHAR(2),
  INCORP_DT      DATE,
  ANNUAL_REV     NUMERIC(18,2),
  RISK_SEG       VARCHAR(20)
);

CREATE TABLE CUST_GRP_XREF (
  GRP_NO         VARCHAR(12) NOT NULL,
  CUST_NO        VARCHAR(12) NOT NULL REFERENCES CUST_MST(CUST_NO),
  REL_CD         VARCHAR(20) NOT NULL, -- PARENT / SUBSIDIARY
  PRIMARY KEY (GRP_NO, CUST_NO)
);

CREATE TABLE LN_FAC (
  FAC_NO         VARCHAR(16) PRIMARY KEY,
  CUST_NO        VARCHAR(12) NOT NULL REFERENCES CUST_MST(CUST_NO),
  PROD_CD        VARCHAR(20) NOT NULL,
  LIM_AMT        NUMERIC(18,2) NOT NULL,
  CCY_CD         CHAR(3) NOT NULL,
  EFF_DT         DATE NOT NULL,
  EXP_DT         DATE,
  FAC_STAT       VARCHAR(20) NOT NULL
);

CREATE TABLE LN_ACCT (
  LN_NO          VARCHAR(16) PRIMARY KEY,
  FAC_NO         VARCHAR(16) NOT NULL REFERENCES LN_FAC(FAC_NO),
  CUST_NO        VARCHAR(12) NOT NULL REFERENCES CUST_MST(CUST_NO),
  LN_TYP         VARCHAR(24) NOT NULL,
  ORIG_AMT       NUMERIC(18,2) NOT NULL,
  OUT_BAL        NUMERIC(18,2) NOT NULL,
  INT_RATE       NUMERIC(8,4),
  TERM_MTH       INTEGER,
  BOOK_DT        DATE NOT NULL,
  MAT_DT         DATE,
  LN_STAT        VARCHAR(20) NOT NULL
);

CREATE TABLE LN_AGR (
  AGR_NO         VARCHAR(16) PRIMARY KEY,
  FAC_NO         VARCHAR(16) NOT NULL REFERENCES LN_FAC(FAC_NO),
  AGR_DT         DATE NOT NULL,
  LAW_JUR        VARCHAR(40),
  DOC_STAT       VARCHAR(20)
);

CREATE TABLE GUAR_XREF (
  LN_NO          VARCHAR(16) NOT NULL REFERENCES LN_ACCT(LN_NO),
  GUAR_CUST_NO   VARCHAR(12) NOT NULL REFERENCES CUST_MST(CUST_NO),
  GUAR_AMT       NUMERIC(18,2),
  GUAR_TYP       VARCHAR(20),
  PRIMARY KEY (LN_NO, GUAR_CUST_NO)
);

CREATE TABLE COLL_MST (
  COLL_NO        VARCHAR(16) PRIMARY KEY,
  COLL_TYP       VARCHAR(30) NOT NULL,
  COLL_DESC      VARCHAR(200),
  MKT_VAL        NUMERIC(18,2),
  VAL_DT         DATE,
  CCY_CD         CHAR(3)
);

CREATE TABLE COLL_LINK (
  LN_NO          VARCHAR(16) NOT NULL REFERENCES LN_ACCT(LN_NO),
  COLL_NO        VARCHAR(16) NOT NULL REFERENCES COLL_MST(COLL_NO),
  CHG_AMT        NUMERIC(18,2),
  LIEN_RANK      INTEGER,
  PRIMARY KEY (LN_NO, COLL_NO)
);

CREATE TABLE COV_MST (
  COV_NO         VARCHAR(16) PRIMARY KEY,
  COV_CD         VARCHAR(30) NOT NULL,
  COV_DESC       VARCHAR(240),
  TEST_FREQ      VARCHAR(20)
);

CREATE TABLE LN_COV_XREF (
  LN_NO          VARCHAR(16) NOT NULL REFERENCES LN_ACCT(LN_NO),
  COV_NO         VARCHAR(16) NOT NULL REFERENCES COV_MST(COV_NO),
  THRESHOLD_VAL  NUMERIC(12,4),
  OPERATOR_CD    VARCHAR(5),
  PRIMARY KEY (LN_NO, COV_NO)
);

CREATE TABLE LN_RATING_HIST (
  RATING_ID      VARCHAR(16) PRIMARY KEY,
  CUST_NO        VARCHAR(12) NOT NULL REFERENCES CUST_MST(CUST_NO),
  LN_NO          VARCHAR(16) REFERENCES LN_ACCT(LN_NO),
  RATING_CD      VARCHAR(12) NOT NULL,
  PD_PCT         NUMERIC(8,5),
  AS_OF_DT       DATE NOT NULL,
  RATING_SRC     VARCHAR(30)
);

CREATE TABLE LN_PAY_TXN (
  TXN_NO         VARCHAR(16) PRIMARY KEY,
  LN_NO          VARCHAR(16) NOT NULL REFERENCES LN_ACCT(LN_NO),
  POST_DT        DATE NOT NULL,
  PRIN_AMT       NUMERIC(18,2),
  INT_AMT        NUMERIC(18,2),
  TXN_STAT       VARCHAR(20)
);

