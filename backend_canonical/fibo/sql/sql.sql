SELECT
    a.LOAN_ID,
    a.BORR_CUST_ID,
    c.LEGAL_NAME AS BORROWER_NAME,
    a.ORIG_AMT AS ORIGINAL_AMOUNT,
    a.OUT_BAL AS OUTSTANDING_BALANCE,
    a.CCY_CD AS CURRENCY,
    a.MATURITY_DT
FROM LN_ACCT a
JOIN CUST_MST c
    ON a.BORR_CUST_ID = c.CUST_ID
WHERE a.STATUS_CD = 'ACTIVE';

SELECT
    c.CUST_ID,
    c.LEGAL_NAME,
    COUNT(a.LOAN_ID) AS LOAN_COUNT,
    SUM(a.OUT_BAL) AS TOTAL_OUTSTANDING_BALANCE,
    SUM(a.ORIG_AMT) AS TOTAL_ORIGINAL_AMOUNT
FROM CUST_MST c
JOIN LN_ACCT a
    ON c.CUST_ID = a.BORR_CUST_ID
GROUP BY
    c.CUST_ID,
    c.LEGAL_NAME;

SELECT
    f.FAC_ID,
    f.FACILITY_NAME,
    f.COMMIT_AMT AS COMMITMENT_AMOUNT,
    SUM(a.OUT_BAL) AS UTILIZED_AMOUNT,
    f.COMMIT_AMT - SUM(a.OUT_BAL) AS AVAILABLE_AMOUNT
FROM LN_FAC f
JOIN LN_ACCT a
    ON f.FAC_ID = a.FAC_ID
GROUP BY
    f.FAC_ID,
    f.FACILITY_NAME,
    f.COMMIT_AMT;


SELECT
    a.LOAN_ID,
    a.OUT_BAL AS OUTSTANDING_BALANCE,
    SUM(cl.ALLOC_AMT) AS COLLATERAL_VALUE,
    SUM(cl.ALLOC_AMT) / NULLIF(a.OUT_BAL, 0) AS COLLATERAL_COVERAGE
FROM LN_ACCT a
JOIN COLL_LINK cl
    ON a.LOAN_ID = cl.LOAN_ID
GROUP BY
    a.LOAN_ID,
    a.OUT_BAL;


SELECT
    a.LOAN_ID,
    c.COV_NAME,
    x.THRESHOLD_VAL,
    x.ACTUAL_VAL,
    x.COMPLIANCE_STATUS_CD
FROM LN_ACCT a
JOIN LN_COV_XREF x
    ON a.LOAN_ID = x.LOAN_ID
JOIN COV_MST c
    ON x.COV_ID = c.COV_ID
WHERE x.COMPLIANCE_STATUS_CD = 'BREACH';


SELECT
    g.GROUP_CUST_ID,
    parent.LEGAL_NAME AS GROUP_NAME,
    member.CUST_ID,
    member.LEGAL_NAME AS MEMBER_NAME,
    SUM(a.OUT_BAL) AS TOTAL_EXPOSURE
FROM CUST_GRP_XREF g
JOIN CUST_MST parent
    ON g.GROUP_CUST_ID = parent.CUST_ID
JOIN CUST_MST member
    ON g.CUST_ID = member.CUST_ID
JOIN LN_ACCT a
    ON member.CUST_ID = a.BORR_CUST_ID
GROUP BY
    g.GROUP_CUST_ID,
    parent.LEGAL_NAME,
    member.CUST_ID,
    member.LEGAL_NAME;


    